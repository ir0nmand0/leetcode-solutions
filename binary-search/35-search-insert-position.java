// LeetCode: перед вставкой переименуй класс в Solution
//
// 35. Search Insert Position (Easy)
//
// Дан отсортированный массив уникальных целых чисел nums и целое число target.
// Если target есть — вернуть его индекс.
// Если нет — вернуть индекс куда бы его вставили чтобы массив остался отсортированным.
//
// Это 704 (Binary Search) + одно изменение в конце:
// - 704: target не найден → return -1
// - 35:  target не найден → return left  (место вставки)
//
// Подход: Binary Search — два указателя + выбрасывание половины.
// Массив отсортирован → середина всегда делит его на "точно меньше" и "точно больше".
// Каждый шаг выбрасываем половину — поэтому O(log n), а не O(n).
//
// ПОЧЕМУ left <= right, А НЕ left < right:
// Когда left == right — оба указателя смотрят на один элемент.
// Это последний кандидат — его нужно проверить.
// left < right → цикл пропустит последний элемент → баг на граничных случаях.
// left <= right → проверяем всё включая одиночный остаток.
//
// ПОЧЕМУ mid = left + (right - left) / 2, А НЕ (left + right) / 2:
// Integer.MAX_VALUE = 2_147_483_647
//
// ❌ Наивный: (left + right) / 2
//    left = 2_000_000_000, right = 2_100_000_000
//    шаг 1: left + right = 4_100_000_000  ← уже здесь переполнение!
//    шаг 2: int "перекручивается" → -194_967_296  (отрицательное)
//    шаг 3: -194_967_296 / 2 = -97_483_648
//    шаг 4: nums[-97_483_648] → 💥 ArrayIndexOutOfBoundsException
//
// ✅ Безопасный: left + (right - left) / 2
//    left = 2_000_000_000, right = 2_100_000_000
//    шаг 1: right - left = 100_000_000  ← просто расстояние между указателями
//    шаг 2: 100_000_000 / 2 = 50_000_000
//    шаг 3: 2_000_000_000 + 50_000_000 = 2_050_000_000  ✅
//
// Математически одно и то же — разница только в порядке операций:
//    left + (right - left) / 2 = left/2 + right/2 = (left + right) / 2
//    Но сначала вычитаем → получаем маленькое расстояние → взрыва нет.
//
// На LeetCode массивы маленькие — не сломается. Но привычка писать
// безопасный вариант профессиональная — в проде int[] легко на 2 млрд.
//
// КАК СУЖАЕТСЯ ОКНО:
// nums[mid] < target → mid проверен, target правее  → left  = mid + 1
// nums[mid] > target → mid проверен, target левее   → right = mid - 1
// nums[mid] == target → нашли                       → return mid
// +1 и -1 обязательны — mid уже проверен, перешагиваем через него.
// Без +1/-1 mid не сдвинется если left==right → бесконечный цикл.
//
// ПОЧЕМУ ИМЕННО left — ВСЯ СУТЬ ЗАДАЧИ:
//
// left двигается вправо ТОЛЬКО когда nums[mid] < target.
// Значит left говорит: "всё что левее меня — точно меньше target".
//
// right двигается влево ТОЛЬКО когда nums[mid] > target.
// Значит right говорит: "всё что правее меня — точно больше target".
//
// Цикл заканчивается когда left ПЕРЕШАГИВАЕТ через right:
//
//   до перешагивания:            после:
//   [1,  3,  5,  6]              [1,  3,  5,  6]
//    ↑                                ↑   ↑
// right                             right left
// left
//
// left останавливается ровно на первом элементе который больше target —
// то есть на месте куда target нужно вставить.
//
// Примеры итераций:
// target=2 → left=1 (перед 3)   ✅
// target=0 → left=0 (перед 1)   ✅  граничный: вставка в начало
// target=7 → left=4 (после 6)   ✅  граничный: вставка в конец
class SearchInsertPosition {

    // ========================================================================
    // Решение — Binary Search + return left вместо return -1
    // ========================================================================
    // Время:  O(log n) — каждую итерацию выбрасываем половину
    // Память: O(1)     — только три переменных, нет рекурсии
    public int searchInsert(int[] nums, int target) {

        // Границы поиска — изначально весь массив
        int left  = 0;
        int right = nums.length - 1;

        // left == right → один кандидат остался, его тоже проверяем (<=, не <)
        while (left <= right) {

            // Безопасная формула mid — right - left это просто расстояние
            // между указателями, никогда не переполнит int в отличие от left + right
            int mid = left + (right - left) / 2;

            // Нашли — позиция существует, возвращаем индекс
            if (nums[mid] == target) {
                return mid;
            }

            // Середина МЕНЬШЕ target → target правее → левая граница за mid
            // mid проверен и не подходит → перешагиваем через него: mid + 1
            if (nums[mid] < target) {
                left = mid + 1;
            } else {
                // Середина БОЛЬШЕ target → target левее → правая граница за mid
                // mid проверен и не подходит → перешагиваем через него: mid - 1
                right = mid - 1;
            }
        }

        // target не найден.
        // left перешагнул через right — они поменялись местами.
        // left стоит на первом элементе который больше target —
        // это ровно то место куда нужно вставить target.
        // В отличие от 704 где мы возвращали -1 — здесь возвращаем left.
        return left;
    }

    public static void main(String[] args) {
        var sol = new SearchInsertPosition();

        // Элемент существует → 2
        System.out.println(sol.searchInsert(new int[]{1, 3, 5, 6}, 5));

        // Вставка в середину → 1  (между 1 и 3)
        System.out.println(sol.searchInsert(new int[]{1, 3, 5, 6}, 2));

        // Вставка в конец → 4  (после 6)
        // left перешагивает right за пределы массива
        System.out.println(sol.searchInsert(new int[]{1, 3, 5, 6}, 7));

        // Вставка в начало → 0  (перед 1)
        // right уходит в -1, left остаётся на 0
        System.out.println(sol.searchInsert(new int[]{1, 3, 5, 6}, 0));

        // Один элемент, совпадает → 0
        // Ловушка: left==right — последний кандидат, входим в цикл благодаря <=
        System.out.println(sol.searchInsert(new int[]{1}, 1));

        // Один элемент, не совпадает, вставка перед ним → 0
        System.out.println(sol.searchInsert(new int[]{3}, 1));

        // Один элемент, не совпадает, вставка после него → 1
        System.out.println(sol.searchInsert(new int[]{1}, 3));
    }
}
