// LeetCode: перед вставкой переименуй класс в Solution
//
// 33. Search in Rotated Sorted Array (Medium)
//
// Отсортированный массив был повёрнут в некоторой точке — неизвестной тебе.
// Найти target и вернуть его индекс. Если не найден — вернуть -1.
//
// Это докрут 704 (Binary Search) — механика та же, меняется только условие:
// - 704: сравниваем target с mid  →  куда двигаться
// - 33:  сначала определяем какая половина отсортирована,
//        затем проверяем зажат ли target внутри неё  →  куда двигаться
//
// ЧТО ЗНАЧИТ "ПОВЁРНУТ":
// исходный: [0, 1, 2, 4, 5, 6, 7]
// повёрнут: [4, 5, 6, 7, 0, 1, 2]
//                       ↑
//                  точка разрыва
// После поворота массив разбивается на две части — каждая отсортирована,
// но между ними есть разрыв. Одна из двух половин [left..mid] или [mid..right]
// ВСЕГДА гарантированно отсортирована — это ключевое наблюдение.
//
// КАК ОПРЕДЕЛИТЬ КАКАЯ ПОЛОВИНА ОТСОРТИРОВАНА:
// Сравниваем nums[left] и nums[mid] — всего два числа:
//
// nums[left] <= nums[mid]  →  левая половина [left..mid] отсортирована
// [4, 5, 6, 7, 0, 1, 2]
//  ↑           ↑
// left        mid          [4,5,6,7] — отсортирована ✅
//
// nums[left] > nums[mid]   →  левая НЕ отсортирована → правая точно отсортирована
// [6, 7, 0, 1, 2, 4, 5]
//  ↑           ↑
// left        mid          [6,7,0,1] — не отсортирована → [2,4,5] точно отсортирована ✅
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СРАВНИТЬ TARGET С MID КАК В 704:
// В 704 весь массив отсортирован — target < mid значит он точно левее.
// Здесь это не работает — target может быть меньше mid но лежать правее разрыва:
//   [4, 5, 6, 7, 0, 1, 2]  target=0
//   nums[mid]=7, target=0 < 7  →  пойдём влево  💥  target справа!
//
// Поэтому сначала определяем где порядок гарантирован,
// затем зажимаем target между границами этой половины —
// только так можно точно сказать лежит ли он там.
//
// КАК РЕШИТЬ КУДА ДВИГАТЬСЯ — ДОКРУТ 704:
// В 704 вопрос был: target больше или меньше mid?
// В 33  вопрос:     target зажат внутри отсортированной половины или нет?
//
// Вместо одного сравнения — два (target зажат между границами):
// 704: nums[mid] < target
// 33:  nums[left] <= target && target < nums[mid]
//
// ПОЧЕМУ В ЗАЖИМЕ mid СТРОГОЕ (<), А left И right НЕСТРОГИЕ (<=):
//
// mid   → строгое  < / >  потому что уже проверен строчкой выше:
//         if (nums[mid] == target) return mid  — незачем включать снова.
//
// left  → нестрогое <=    потому что ещё не проверялся как кандидат —
//         только как граница. Target может лежать прямо на нём.
//
// right → нестрогое <=    по той же причине — граница, не кандидат.
//
// Итого зажим выглядит так:
//   левая:  nums[left] <= target && target < nums[mid]
//   правая: nums[mid]  <  target && target <= nums[right]
//
// Левая половина отсортирована:
//   target внутри [nums[left]..nums[mid]]  →  right = mid - 1  (идём влево)
//   иначе target где-то правее            →  left  = mid + 1  (идём вправо)
//
// Правая половина отсортирована:
//   target внутри [nums[mid]..nums[right]] →  left  = mid + 1  (идём вправо)
//   иначе target где-то левее             →  right = mid - 1  (идём влево)
//
// ПОЧЕМУ left <= right, А НЕ left < right:
// Когда left == right — оба указателя смотрят на один элемент.
// Это последний кандидат — его нужно проверить.
// left < right → цикл пропустит последний элемент → баг на граничных случаях.
// left <= right → проверяем всё включая одиночный остаток.
//
// ПОЧЕМУ mid = left + (right - left) / 2, А НЕ (left + right) / 2:
// Integer.MAX_VALUE = 2_147_483_647
//
// ❌ Наивный: (left + right) / 2
//    left = 2_000_000_000, right = 2_100_000_000
//    шаг 1: left + right = 4_100_000_000  ← уже здесь переполнение!
//    шаг 2: int "перекручивается" → -194_967_296  (отрицательное)
//    шаг 3: -194_967_296 / 2 = -97_483_648
//    шаг 4: nums[-97_483_648] → 💥 ArrayIndexOutOfBoundsException
//
// ✅ Безопасный: left + (right - left) / 2
//    left = 2_000_000_000, right = 2_100_000_000
//    шаг 1: right - left = 100_000_000  ← просто расстояние между указателями
//    шаг 2: 100_000_000 / 2 = 50_000_000
//    шаг 3: 2_000_000_000 + 50_000_000 = 2_050_000_000  ✅
//
// Математически одно и то же — разница только в порядке операций:
//    left + (right - left) / 2 = left/2 + right/2 = (left + right) / 2
//    Но сначала вычитаем → получаем маленькое расстояние → взрыва нет.
//
// КАК СУЖАЕТСЯ ОКНО:
// +1 и -1 обязательны — mid уже проверен, перешагиваем через него.
// Без +1/-1 mid не сдвинется если left==right → бесконечный цикл.
class SearchInRotatedSortedArray {

    // ========================================================================
    // Решение — Binary Search с определением отсортированной половины
    // ========================================================================
    // Время:  O(log n) — каждую итерацию выбрасываем половину
    // Память: O(1)     — только три переменных, нет рекурсии
    public int search(int[] nums, int target) {

        // Границы поиска — изначально весь массив
        int left  = 0;
        int right = nums.length - 1;

        // left == right → один кандидат остался, его тоже проверяем (<=, не <)
        while (left <= right) {

            // Безопасная формула mid — right - left это просто расстояние
            // между указателями, никогда не переполнит int в отличие от left + right
            int mid = left + (right - left) / 2;

            // Нашли — возвращаем индекс.
            // mid проверен здесь — поэтому в зажиме ниже mid строгое < / >
            if (nums[mid] == target) {
                return mid;
            }

            // Определяем какая половина отсортирована — сравниваем left и mid.
            // Два числа дают полную картину: где разрыв, а где порядок.
            if (nums[left] <= nums[mid]) {

                // Левая половина [left..mid] отсортирована.
                // Нельзя просто сравнить target с mid как в 704 — разрыв мог
                // оказаться справа, и target < mid не значит что он в левой.
                // Зажимаем target между границами:
                //   left  нестрогое <= : ещё не проверялся как кандидат, только граница
                //   mid   строгое    < : уже проверен строчкой выше
                if (nums[left] <= target && target < nums[mid]) {
                    right = mid - 1;  // target точно внутри левой  → идём влево
                } else {
                    left = mid + 1;   // target вне диапазона левой → идём вправо
                }

            } else {

                // Левая половина НЕ отсортирована — значит разрыв находится в ней.
                // Других вариантов нет — разрыв всегда ровно в одной из двух половин.
                // Следовательно правая половина [mid..right] ГАРАНТИРОВАННО отсортирована.
                // Та же логика зажима — но зеркально:
                //   mid   строгое    < : уже проверен строчкой выше
                //   right нестрогое <= : ещё не проверялся как кандидат, только граница
                if (nums[mid] < target && target <= nums[right]) {
                    left = mid + 1;   // target точно внутри правой  → идём вправо
                } else {
                    right = mid - 1;  // target вне диапазона правой → идём влево
                }
            }
        }

        // Окно схлопнулось — target не найден
        return -1;
    }

    public static void main(String[] args) {
        var sol = new SearchInRotatedSortedArray();

        // Базовый кейс — target в правой (неотсортированной) части → 4
        System.out.println(sol.search(new int[]{4, 5, 6, 7, 0, 1, 2}, 0));

        // Target не существует → -1
        System.out.println(sol.search(new int[]{4, 5, 6, 7, 0, 1, 2}, 3));

        // Один элемент совпадает → 0
        // Ловушка: left==right — последний кандидат, входим в цикл благодаря <=
        System.out.println(sol.search(new int[]{1}, 1));

        // Один элемент не совпадает → -1
        System.out.println(sol.search(new int[]{1}, 0));

        // Target в левой (отсортированной) части → 1
        System.out.println(sol.search(new int[]{4, 5, 6, 7, 0, 1, 2}, 5));

        // Поворот в начале — массив почти не повёрнут → 4
        System.out.println(sol.search(new int[]{1, 3, 5, 6, 7, 0}, 7));

        // Поворот в конце — массив почти не повёрнут → 0
        System.out.println(sol.search(new int[]{2, 4, 5, 6, 7, 1}, 2));
    }
}