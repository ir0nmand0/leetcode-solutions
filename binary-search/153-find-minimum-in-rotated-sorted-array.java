// LeetCode: перед вставкой переименуй класс в Solution
//
// 153. Find Minimum in Rotated Sorted Array (Medium)
//
// Дан отсортированный массив который был повёрнут в некоторой точке.
// Найти минимальный элемент. Сложность O(log n).
//
// Это докрут 33 (Search in Rotated Sorted Array) — но без target.
// Вместо поиска конкретного элемента ищем точку разрыва — минимум всегда там.
//
// ЧТО ЗНАЧИТ "ПОВЁРНУТ":
// исходный: [0, 1, 2, 4, 5, 6, 7]
// повёрнут: [4, 5, 6, 7, 0, 1, 2]
//                       ↑
//                  точка разрыва — здесь лежит минимум
//
// ПОЧЕМУ mid vs right, А НЕ left vs mid КАК В 33:
// В 33 мы сравнивали left и mid — но там был target как ориентир.
// left vs mid работает только в паре с target:
//   "левая отсортирована → target внутри неё или нет?"
// Здесь target нет — left не является ориентиром относительно минимума.
//
// mid vs right работает сам по себе:
// Минимум НИКОГДА не находится правее right — это инвариант.
// Поэтому сравниваем mid с right и сразу знаем где разрыв:
//
//   nums[mid] > nums[right]  →  разрыв в правой половине  →  left  = mid + 1
//   [4, 5, 6, 7, 0, 1, 2]
//               ↑        ↑
//              mid     right     7 > 2 → минимум правее mid ✅
//
//   nums[mid] < nums[right]  →  разрыв в левой половине   →  right = mid
//   [6, 7, 0, 1, 2, 4, 5]
//               ↑        ↑
//              mid     right     1 < 5 → минимум левее mid (или сам mid) ✅
//
// ПЯТЬ КЛЮЧЕВЫХ ПРАВИЛ — ЧЕМ ОТЛИЧАЕТСЯ ОТ 704 / 33:
//
// 1. mid vs right, а не left vs mid
//    (left не ориентир относительно минимума — работает только с target)
//
// 2. nums[mid] > nums[right] → left  = mid + 1  (разрыв справа)
//    nums[mid] < nums[right] → right = mid       (разрыв слева)
//
// 3. цикл: left < right вместо left <= right
//    Когда left == right — оба смотрят на минимум, ответ уже найден.
//    left <= right с right = mid дало бы бесконечный цикл:
//    left=0, right=0 → mid=0 → right = mid = 0 → вечный цикл 💥
//
// 4. сдвиг: right = mid вместо right = mid - 1
//    mid может оказаться минимумом — нельзя выбрасывать.
//    В 33 мы знали что mid != target и выбрасывали его смело.
//    Здесь такой гарантии нет.
//
// 5. ответ: return nums[left] вместо return -1
//    left и right сошлись на минимуме — возвращаем его значение.
//
// ПОЧЕМУ left <= right, А НЕ left < right (напоминание из 704):
// Когда left == right — оба указателя смотрят на один элемент.
// В 704/33 это последний кандидат которого нужно проверить → left <= right.
// Здесь когда left == right — ответ уже найден, заходить не нужно → left < right.
//
// ПОЧЕМУ mid = left + (right - left) / 2, А НЕ (left + right) / 2:
// Integer.MAX_VALUE = 2_147_483_647
//
// ❌ Наивный: (left + right) / 2
//    left = 2_000_000_000, right = 2_100_000_000
//    шаг 1: left + right = 4_100_000_000  ← уже здесь переполнение!
//    шаг 2: int "перекручивается" → -194_967_296  (отрицательное)
//    шаг 3: -194_967_296 / 2 = -97_483_648
//    шаг 4: nums[-97_483_648] → 💥 ArrayIndexOutOfBoundsException
//
// ✅ Безопасный: left + (right - left) / 2
//    left = 2_000_000_000, right = 2_100_000_000
//    шаг 1: right - left = 100_000_000  ← просто расстояние между указателями
//    шаг 2: 100_000_000 / 2 = 50_000_000
//    шаг 3: 2_000_000_000 + 50_000_000 = 2_050_000_000  ✅
//
// Математически одно и то же — разница только в порядке операций:
//    left + (right - left) / 2 = left/2 + right/2 = (left + right) / 2
//    Но сначала вычитаем → получаем маленькое расстояние → взрыва нет.
class FindMinimumInRotatedSortedArray {

    // ========================================================================
    // Решение — Binary Search по точке разрыва
    // ========================================================================
    // Время:  O(log n) — каждую итерацию выбрасываем половину
    // Память: O(1)     — только три переменных, нет рекурсии
    public int findMin(int[] nums) {

        // Границы поиска — изначально весь массив
        int left  = 0;
        int right = nums.length - 1;

        // left < right, не <=:
        // когда left == right — оба на минимуме, ответ найден, заходить не нужно.
        // left <= right с right = mid дало бы бесконечный цикл.
        while (left < right) {

            // Безопасная формула mid — right - left это просто расстояние
            // между указателями, никогда не переполнит int в отличие от left + right
            int mid = left + (right - left) / 2;

            if (nums[mid] > nums[right]) {
                // mid больше right → разрыв в правой половине → минимум правее mid.
                // mid точно не минимум — выбрасываем его: left = mid + 1
                left = mid + 1;
            } else {
                // mid меньше right → разрыв в левой половине → минимум левее mid
                // или сам mid является минимумом — нельзя выбрасывать: right = mid
                right = mid;
            }
        }

        // left == right — оба сошлись на минимуме
        return nums[left];
    }

    public static void main(String[] args) {
        var sol = new FindMinimumInRotatedSortedArray();

        // Базовый кейс — минимум в правой части → 1
        System.out.println(sol.findMin(new int[]{3, 4, 5, 1, 2}));

        // Минимум в середине → 0
        System.out.println(sol.findMin(new int[]{4, 5, 6, 7, 0, 1, 2}));

        // Поворота нет — минимум первый элемент → 11
        System.out.println(sol.findMin(new int[]{11, 13, 15, 17}));

        // Один элемент → 1
        // left==right сразу, цикл не входит, возвращаем nums[0]
        System.out.println(sol.findMin(new int[]{1}));

        // Два элемента, минимум второй → 1
        System.out.println(sol.findMin(new int[]{2, 1}));

        // Два элемента, минимум первый → 1
        System.out.println(sol.findMin(new int[]{1, 2}));

        // Поворот на последнем элементе → 1
        System.out.println(sol.findMin(new int[]{2, 3, 4, 5, 1}));
    }
}
