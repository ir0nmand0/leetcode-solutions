// LeetCode: перед вставкой переименуй класс в Solution
//
// 424. Longest Repeating Character Replacement (Medium)
//
// Дана строка s (только заглавные английские буквы) и число k.
// Можно заменить ЛЮБЫЕ k символов в строке на любые другие.
// Нужно найти длину самой длинной подстроки,
// в которой все символы одинаковые (после замен).
//
// Пример: s = "AABABBA", k = 1
// Заменяем одну 'B' → "AAAAABA" или подобное → ответ 4
//
// Подход: Sliding Window + частотный массив.
// Ключевая идея: в окне [left..right] самый частый символ оставляем,
// а все остальные — это те, что нужно заменить.
// Если (длина окна - количество самого частого символа) > k — окно невалидно, сжимаем.
class LongestRepeatingCharReplacement {

    // Временная сложность: O(n) — каждый символ обрабатывается максимум дважды (right++ и left++)
    // Пространственная сложность: O(1) — массив всегда 26 элементов
    //
    // ГЛАВНАЯ ИДЕЯ (Sliding Window):
    // Окно валидно если: windowSize - maxFreq <= k
    // Смысл: (все символы в окне) - (самый частый символ) = символы под замену
    // Если символов под замену не больше k — окно валидно.
    //
    // ЛАЙФХАК с массивом:
    // freq[c - 'A'] хранит количество символа c ВНУТРИ ТЕКУЩЕГО ОКНА.
    // Не во всей строке — а именно между left и right.
    // Синхронизация: right++ → freq[idx]++, left++ → freq[idx]--
    // Благодаря charCode - 'A' получаем O(1) доступ без хэшмапы.
    //
    // ПОЧЕМУ НЕ НАДО СКАНИРОВАТЬ 26 ЭЛЕМЕНТОВ:
    // Новый чемпион (maxFreq) может появиться ТОЛЬКО в одном месте —
    // когда добавляем символ справа (right++).
    // При left++ частоты только падают — чемпион появиться не может.
    // Значит один кандидат → одно сравнение → O(1).
    //
    // ПОЧЕМУ maxFreq МОЖНО НЕ УМЕНЬШАТЬ:
    // Нас интересует только РАСШИРЕНИЕ окна.
    // Устаревший maxFreq не даст окну вырасти — просто будет слайдить.
    // Ложный позитив возможен только при size меньше текущего maxWindow —
    // то есть maxWindow в этот момент всё равно не обновится.
    // Новый реальный чемпион придёт только через right++ — там всё честно.
    public int characterReplacement(String s, int k) {

        // Частотный массив — хранит кол-во каждого символа в текущем окне.
        // Индекс = charCode - 'A': 'A'=0, 'B'=1, ..., 'Z'=25
        // ВАЖНО: это не глобальные частоты строки, а только внутри [left, right]
        int[] freq = new int[26];

        int left = 0;      // левая граница окна
        int maxFreq = 0;   // частота чемпиона — только растёт, никогда не падает
        int maxWindow = 0; // итоговый ответ

        for (int right = 0; right < s.length(); right++) {

            // Индекс символа в freq через арифметику чаров — O(1), без хэшмапы
            int idx = s.charAt(right) - 'A';

            // Добавляем правый символ в окно — синхронизируем freq с границами
            freq[idx]++;

            // Единственное место где может появиться новый чемпион.
            // Только что добавленный символ — единственный кандидат,
            // потому что только его частота только что выросла.
            // Все остальные символы внутри окна не изменились.
            maxFreq = Math.max(maxFreq, freq[idx]);

            // Размер текущего окна
            int windowSize = right - left + 1;

            // Проверяем инвариант: сколько символов нужно заменить?
            // windowSize - maxFreq = все символы кроме чемпиона = кандидаты на замену
            if (windowSize - maxFreq > k) {
                // Инвариант нарушен — сдвигаем левую границу.
                // Не shrink (сжимаем) а slide (едем вправо как каретка).
                // Синхронизируем freq: убираем левый символ из окна.
                freq[s.charAt(left) - 'A']--;
                left++;

                // maxFreq НЕ обновляем — он мог устареть но нам всё равно.
                // Устаревший maxFreq = высокая планка которую сложно перепрыгнуть.
                // Окно будет слайдить пока правый символ не наберёт достаточно частоты
                // чтобы побить планку — вот тогда окно расширится и ответ обновится.

                // windowSize уменьшился на 1 после left++ —
                // это не прогресс, maxWindow не обновляем.

            } else {
                // Инвариант соблюдён — окно валидно.
                // Обновляем ответ только здесь, только при реальном прогрессе.
                maxWindow = Math.max(maxWindow, windowSize);
            }
        }

        return maxWindow;
    }

    public static void main(String[] args) {
        var sol = new LongestRepeatingCharReplacement();

        // "AABABBA", k=1 → заменяем одну 'B' → "AAAA" → ответ 4
        System.out.println(sol.characterReplacement("AABABBA", 1)); // 4

        // "ABAB", k=2 → заменяем обе 'B' → "AAAA" → ответ 4
        System.out.println(sol.characterReplacement("ABAB", 2));    // 4

        // "AABA", k=0 → замен нет → самая длинная "AA" → ответ 2
        System.out.println(sol.characterReplacement("AABA", 0));    // 2
    }
}
