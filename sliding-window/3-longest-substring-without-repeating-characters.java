import java.util.*;

// LeetCode: перед вставкой переименуй класс в Solution
//
// 3. Longest Substring Without Repeating Characters (Medium)
//
// Дана строка s.
// Нужно найти длину самого длинного подряд идущего фрагмента строки,
// в котором нет повторяющихся символов.
//
// Важно:
// - Подстрока = символы идут подряд (не подпоследовательность!)
// - Вернуть нужно только длину
//
// Подход: Sliding Window — гибкое окно + массив lastSeen.
//
// Ключевая идея — хранить не флаг "видели/не видели", а ПОЗИЦИЮ
// (индекс) последнего вхождения символа. Это даёт два преимущества:
//
// 1. Знаем КУДА прыгнуть:
//    left = lastSeen[ch] + 1 — перепрыгиваем ровно за дубликат.
//    Без позиции пришлось бы двигать left по +1 в while-цикле → O(n²).
//
// 2. Знаем НУЖНО ЛИ прыгать:
//    Проверка lastSeen[ch] >= left — дубликат внутри текущего окна.
//    Если lastSeen[ch] < left — тот символ уже за пределами окна,
//    он нам не мешает, прыгать не нужно.
//
// Почему max(left, lastSeen[ch] + 1):
//    left мог уже уехать правее из-за другого дубликата.
//    Без max() left откатится назад и захватит старые дубликаты.
//    Пример: "abba" — на шаге i=3 (символ 'a') lastSeen['a']=0,
//    но left уже на 2. Без max left стал бы 1 → окно "bba" → баг.
//
// Почему left и i не пересекутся:
//    lastSeen[ch] + 1 максимум равен i (дубликат на предыдущем шаге).
//    В этом случае left = i, окно размер 1 — сравнялись, но не
//    пересеклись. Дальше i уйдёт вперёд на следующей итерации.
//
// Почему массив на 128, а не на 26:
//    По условию задачи строка может содержать буквы, цифры, пробелы
//    и спецсимволы — весь ASCII. Массив на 26 покроет только a-z.
class LongestSubstringNoRepeat {

    // ========================================================================
    // Решение v1 — HashSet + while-цикл (первый рабочий вариант)
    // ========================================================================
    // Время:  O(n) амортизированно — каждый символ добавляется/удаляется из set макс. 1 раз
    // Память: O(min(n, размер алфавита)) — set хранит только уникальные символы окна
    //
    // Проблема: при дубликате далеко от left, while делает много шагов.
    // Пример: "abcdefghija" i=10 → while удалит 9 символов по одному.
    //
    // ВАЖНО: условие while — chars.contains(tmp), НЕ chars.contains(s.charAt(left)).
    // Мы ищем конкретный дубликат, а не "любой символ в set".
    // Иначе окно схлопнется до [i, i] каждый раз (удалит всё подряд).
    //
    // public int lengthOfLongestSubstring(String s) {
    //     Set<Character> chars = new HashSet<>();
    //     int left = 0;
    //     int max = 0;
    //
    //     for (int i = 0; i < s.length(); i++) {
    //         char tmp = s.charAt(i);
    //
    //         // Сжимаем слева, пока ДУБЛИКАТ не вылетит из set
    //         while (chars.contains(tmp)) {
    //             chars.remove(s.charAt(left));
    //             ++left;
    //         }
    //
    //         chars.add(tmp);
    //         max = Math.max(max, i - left + 1);
    //     }
    //
    //     return max;
    // }

    // ========================================================================
    // Решение v2 — lastSeen[] + прямой прыжок (оптимизация)
    // ========================================================================
    // Время:  O(n) — один проход, без вложенных циклов. O(1) на каждый шаг.
    // Память: O(1) — массив фиксированного размера 128
    //
    // Вместо while-цикла удаления — один прыжок left = lastSeen[ch] + 1.
    // Пример: "abcdefghija" i=10 → lastSeen['a']=0, left=1. Один шаг.
    public int lengthOfLongestSubstring(String s) {
        // Храним последнюю позицию каждого ASCII-символа.
        // -1 означает "ещё не встречался".
        int[] lastSeen = new int[128];
        Arrays.fill(lastSeen, -1);

        int maxLen = 0;  // Глобальный максимум — длина лучшего окна
        int left = 0;    // Левая граница окна

        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);

            // Проверяем: видели ли мы этот символ И находится ли он
            // внутри текущего окна (его сохранённый индекс >= left).
            // Если да — дубликат внутри окна, нужно прыгнуть за него.
            if (lastSeen[ch] >= left) {
                // Перепрыгиваем left за позицию дубликата.
                // max() гарантирует что left никогда не откатится назад.
                left = Math.max(left, lastSeen[ch] + 1);
            }

            // Обновляем позицию символа на текущую.
            // Старая позиция больше не нужна — она затирается.
            // Новая позиция (i) всегда >= left, поэтому пересечения нет.
            lastSeen[ch] = i;

            // ВСЕГДА (не в else!) пересчитываем размер окна.
            // Даже после сдвига left окно может быть большим.
            maxLen = Math.max(maxLen, i - left + 1);
        }

        return maxLen;
    }

    public static void main(String[] args) {
        var sol = new LongestSubstringNoRepeat();

        // Ожидается 3
        System.out.println(sol.lengthOfLongestSubstring("abcabcbb"));

        // Ожидается 1
        System.out.println(sol.lengthOfLongestSubstring("bbbbb"));

        // Ожидается 3
        System.out.println(sol.lengthOfLongestSubstring("pwwkew"));

        // Проверочный кейс: ожидается 2
        System.out.println(sol.lengthOfLongestSubstring("abba"));

        // Проверочный кейс: ожидается 3
        System.out.println(sol.lengthOfLongestSubstring("dvdf"));
    }
}
