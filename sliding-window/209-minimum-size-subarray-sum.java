// LeetCode: перед вставкой переименуй класс в Solution
//
// 209. Minimum Size Subarray Sum (Medium)
//
// Дан target и массив положительных чисел nums.
// Нужно найти минимальную длину подряд идущего подмассива,
// сумма которого >= target.
//
// Если такого подмассива нет — вернуть 0.
//
// Подход: Sliding Window — динамическое окно (расширение + сжатие).
// Окно растёт, пока не выполнится условие по сумме,
// затем сжимается слева, чтобы найти минимальную длину.
class MinSizeSubarraySum {
    // Временная сложность: O(n)
    // Пространственная сложность: O(1)
    public int minSubArrayLen(int target, int[] nums) {
        int sum = 0;      // сумма ТЕКУЩЕГО окна [left..i]
        int left = 0;     // левая граница окна

        // Ищем МИНИМАЛЬНОЕ значение.
        // Поэтому стартуем с очень большого числа, чтобы первый найденный кандидат точно его уменьшил.
        // Здесь minIndexDiff хранит не количество элементов, а РАЗНИЦУ ИНДЕКСОВ: (i - left).
        int minIndexDiff = Integer.MAX_VALUE;

        for (int i = 0; i < nums.length; ++i) {
            // Расширяем окно вправо: добавляем nums[i] в текущую сумму окна
            sum += nums[i];

            // Пока текущее окно валидно (сумма >= target),
            // фиксируем кандидата и пробуем сжимать окно слева.
            while (sum >= target) {

                // ВАЖНО:
                // Здесь фиксируем ТЕКУЩЕЕ валидное окно [left..i].
                // Почему до сжатия?
                // Потому что sum относится именно к текущему окну.
                // После "sum -= nums[left]" это уже будет следующее окно.
                //
                // Ранний подход ломался, потому что проверялось "следующее окно"
                // (после сжатия) как условие для записи ответа.
                // Но если следующее окно уже невалидно, это НЕ отменяет того,
                // что текущее окно было валидным и могло быть лучшим.
                //
                // Здесь сохраняем РАЗНИЦУ ИНДЕКСОВ (i - left), а не длину в элементах.
                // Реальное количество элементов получим в конце через +1.
                int indexDiff = i - left;

                // Ищем минимум среди всех валидных окон
                if (minIndexDiff > indexDiff) {
                    minIndexDiff = indexDiff;
                }

                // Сжимаем окно слева на 1 элемент и продолжаем,
                // пока сумма всё ещё >= target
                sum -= nums[left];
                ++left;
            }
        }

        // Если minIndexDiff не изменился — подходящего окна не было.
        // Иначе переводим "разницу индексов" в "количество элементов":
        // (i - left) + 1
        return minIndexDiff != Integer.MAX_VALUE ? minIndexDiff + 1 : 0;
    }

    public static void main(String[] args) {
        var sol = new MinSizeSubarraySum();

        // Ожидается 2
        System.out.println(sol.minSubArrayLen(7, new int[]{2, 3, 1, 2, 4, 3}));

        // Ожидается 1
        System.out.println(sol.minSubArrayLen(4, new int[]{1, 4, 4}));

        // Ожидается 0
        System.out.println(sol.minSubArrayLen(11, new int[]{1, 1, 1, 1, 1, 1, 1, 1}));
    }
}
