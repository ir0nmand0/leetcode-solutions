import java.util.Arrays;

// LeetCode: перед вставкой переименуй класс в Solution
//
// 567. Permutation in String (Medium)
//
// Даны две строки: s1 и s2 (только строчные английские буквы).
// Нужно вернуть true, если в s2 есть подстрока,
// которая является перестановкой (анаграммой) s1.
//
// Пример: s1 = "ab", s2 = "eidbaooo" → true ("ba" — перестановка "ab")
// Пример: s1 = "ab", s2 = "eidboaoo" → false
//
// Подход: Sliding Window фиксированного размера (длина s1) + два частотных массива.
// Окно длиной s1.length() скользит по s2.
// Если частоты символов в окне совпадают с частотами s1 — это анаграмма.
//
// ## Путь к решению (ошибки на пути)
//
// Ошибка 1 — Якорь и направление:
// Казалось можно найти "опорный символ" s1 в s2 и идти от него назад.
// Не работает — анаграмма не имеет фиксированного порядка, любой якорь ненадёжен.
//
// Ошибка 2 — Перепутал анаграмму с палиндромом:
// Казалось что анаграмма = чтение задом наперёд. Нет, это палиндром.
// Анаграмма — те же буквы в ЛЮБОМ порядке, направление вообще не важно.
//
// Ошибка 3 — Set вместо частот:
// Казалось что s1 можно превратить в Set для быстрой проверки.
// Не работает — Set теряет КОЛИЧЕСТВО символов.
// В анаграмме важно что 'a' встречается ровно столько же раз.
//
// Ошибка 4 — O(n²) интуиция:
// Казалось что для каждой позиции нужно пересчитывать окно заново.
// Нет — окно скользит инкрементально: убираем левый, добавляем правый.
// Один шаг на сдвиг.
class PermutationInString {

    // Временная сложность: O(n * 26) → O(n) — скользим по s2, на каждом шаге сравниваем массивы из 26
    // Пространственная сложность: O(1) — два массива по 26 элементов (константа)
    public boolean checkInclusion(String s1, String s2) {
        if (s1.length() > s2.length()) return false;

        // Два массива на 26 букв:
        // freq1 — эталон, частоты s1, НЕ ТРОГАЕМ после заполнения
        // freq2 — частоты текущего окна в s2, ОБНОВЛЯЕМ при скольжении
        int[] freq1 = new int[26];
        int[] freq2 = new int[26];

        // Индекс символа через char - 'a': 'a'=0, 'b'=1, ..., 'z'=25
        // Никакого HashMap — только арифметика чаров → O(1)

        // Заполняем оба массива для начального окна [0..s1.length()-1]
        for (int i = 0; i < s1.length(); i++) {
            freq1[s1.charAt(i) - 'a']++;
            freq2[s2.charAt(i) - 'a']++;
        }

        // Проверяем начальное окно
        if (Arrays.equals(freq1, freq2)) return true;

        // Скользим окном вправо:
        // — декремент левого символа (уходит из окна)
        // — инкремент правого символа (входит в окно)
        // — сравниваем два массива — совпали = нашли анаграмму
        for (int i = s1.length(); i < s2.length(); i++) {
            freq2[s2.charAt(i) - 'a']++;              // правый входит
            freq2[s2.charAt(i - s1.length()) - 'a']--; // левый уходит

            if (Arrays.equals(freq1, freq2)) return true;
        }

        return false;
    }

    public static void main(String[] args) {
        var sol = new PermutationInString();

        // Ожидается true
        System.out.println(sol.checkInclusion("ab", "eidbaooo"));

        // Ожидается false
        System.out.println(sol.checkInclusion("ab", "eidboaoo"));

        // Ожидается true
        System.out.println(sol.checkInclusion("adc", "dcda"));

        // Ожидается true
        System.out.println(sol.checkInclusion("a", "a"));
    }
}
